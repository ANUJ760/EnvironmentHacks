import { test, expect } from '@playwright/test';

test.use({ viewport: { width: 1680, height: 1080 } });

test('city planning: custom area, mapped inventory, energy/waste balances and reproducible export', async ({ page, request }) => {
  test.skip(process.env.RUN_LIVE_MAP_TESTS !== '1', 'Requires the imported Zurich baseline and running services.');
  test.setTimeout(120000);
  const cities = await (await request.get('/api/gateway/v1/cities')).json();
  const city = cities.find((value: { slug: string }) => value.slug === 'zurich-center');
  const base = `/api/gateway/v1/cities/${city.id}`;
  const feature = (await (await request.get(`${base}/features?category=building&bbox=8.53,47.37,8.55,47.39&limit=1`)).json()).features[0];
  const calculation = await request.post(`${base}/planning-preview`, { data: { geometry: feature.geometry, selection_type: 'building', location: feature.geometry.coordinates[0][0], rainfall_mm: 50, replacement: 'grass' } });
  expect(calculation.status()).toBe(200);
  const report = await calculation.json();
  const metrics = new Map(report.metrics.map((value: { key: string; after: number; delta: number }) => [value.key, value]));
  expect((metrics.get('energy_system') as { delta: number }).delta).toBe(0);
  expect((metrics.get('waste_system') as { delta: number }).delta).toBe(0);
  expect((metrics.get('demolition') as { after: number }).after).toBeCloseTo((metrics.get('recovered') as { after: number }).after + (metrics.get('residual') as { after: number }).after);
  expect(report.provenance.datasets.some((value: { kind: string }) => value.kind === 'air_forecast')).toBe(true);
  expect(report.input_sha256).toMatch(/^[a-f0-9]{64}$/);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`/city/${city.id}`);
  await expect(page.locator('[data-city-map-ready="true"]')).toBeVisible({ timeout: 60000 });
  await expect.poll(async () => Number(await page.locator('[data-rendered-buildings]').getAttribute('data-rendered-buildings')), { timeout: 30000 }).toBeGreaterThan(0);
  expect(await page.locator('body').evaluate(node => getComputedStyle(node).backgroundColor)).toBe('rgb(0, 0, 0)');
  await page.getByRole('button', { name: 'Draw area', exact: true }).click();
  const canvas = await page.locator('canvas').elementHandle();
  const box = (await canvas!.boundingBox())!;
  for (const [x, y] of [[0.48, 0.46], [0.6, 0.46], [0.6, 0.58], [0.48, 0.58]]) await page.mouse.click(box.x + box.width * x!, box.y + box.height * y!);
  await page.getByRole('button', { name: 'Finish area', exact: true }).click();
  await expect(page.locator('[data-planning-panel="area"]')).toBeVisible();
  const left = (await page.getByRole('region', { name: 'Highlighted elements' }).boundingBox())!;
  const summary = (await page.getByRole('region', { name: 'Results summary' }).boundingBox())!;
  const right = (await page.getByRole('complementary', { name: 'Effect specifics' }).boundingBox())!;
  expect(left.x + left.width).toBeLessThanOrEqual(box.x);
  expect(summary.y).toBeGreaterThanOrEqual(box.y + box.height);
  expect(right.x).toBeGreaterThanOrEqual(box.x + box.width);
  await expect(page.locator('[data-removal-results]')).toBeVisible({ timeout: 30000 });
  await page.getByLabel('Intervention action').selectOption('fill');
  await expect(page.locator('[data-impact-metric="fill_volume"]')).toBeVisible({ timeout: 15000 });
  await page.getByRole('button', { name: 'Preview removal on map', exact: true }).click();
  await page.getByRole('button', { name: 'Before', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Before', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'After removal', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export research report', exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/^ecotwin-[a-f0-9]{12}\.json$/);
  await download.saveAs('test-results/planning-report.json');
  await page.screenshot({ path: 'test-results/planning-city.png', fullPage: false });
  expect(await canvas!.evaluate(node => node === document.querySelector('canvas'))).toBe(true);
  expect((await canvas!.boundingBox())!.height).toBeLessThan(1100);
  expect(errors).toEqual([]);
});
